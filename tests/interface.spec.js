import { test, expect } from '@playwright/test';
test('flujo administrador y operador móvil sincronizados', async ({ page, browser }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByLabel('Correo electrónico', { exact: true }).fill('admin@test.local');
  await page.getByLabel('Contraseña', { exact: true }).fill('admin-ui-test-password');
  await page.getByRole('button', { name: 'Ingresar al espacio' }).click();
  await expect(page.locator('#stat-total')).toHaveText('12');
  await page.screenshot({ path: 'test-results/dashboard-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Invitados', exact: true }).click();
  await page.getByRole('button', { name: '+ Invitado', exact: true }).click();
  await page.getByLabel('Nombre completo').fill('Invitada Prueba');
  await page.locator('#modal').getByLabel('Correo electrónico', { exact: true }).fill('prueba@example.com');
  await page.getByRole('button', { name: 'Guardar invitado', exact: true }).click();
  await expect(page.locator('#stat-total')).toHaveText('13');
  await page.getByLabel('Buscar invitados', { exact: true }).fill('Invitada Prueba');
  await page.getByRole('button', { name: 'Ver QR', exact: true }).click();
  await expect(page.getByRole('img', { name: 'QR de ingreso de Invitada Prueba' })).toBeVisible();
  await expect(page.getByText('Envío de correo pendiente de configuración SMTP.')).toBeVisible();
  await page.getByRole('button', { name: 'Cerrar', exact: true }).click();
  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const mobile = await mobileContext.newPage(); await mobile.goto('http://localhost:3100');
  await mobile.getByLabel('Correo electrónico', { exact: true }).fill('operator@test.local');
  await mobile.getByLabel('Contraseña', { exact: true }).fill('operator-ui-test-password');
  await mobile.getByRole('button', { name: 'Ingresar al espacio' }).click();
  await expect(mobile.locator('#scanner-view')).toBeVisible();
  await expect(mobile.getByRole('button', { name: '+ Crear evento' })).toBeHidden();
  await mobile.getByLabel('Buscar para acreditar').fill('Invitada Prueba');
  await mobile.getByRole('button', { name: 'Acreditar', exact: true }).click();
  await mobile.getByRole('button', { name: 'Confirmar acreditación' }).click();
  await expect(mobile.locator('#checkin-result')).toContainText('ACREDITADO');
  await expect(page.locator('#stat-checked')).toHaveText('1');
  expect(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await mobile.screenshot({ path: 'test-results/acreditacion-mobile.png', fullPage: true });
  await mobileContext.close();
  await page.getByRole('button', { name: 'Resumen', exact: true }).click();
  await expect(page.locator('#arrivals')).toContainText('Invitada Prueba');
  expect(errors).toEqual([]);
});
