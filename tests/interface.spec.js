import { test, expect } from '@playwright/test';
import jsQR from 'jsqr';
import { PNG } from 'pngjs';
test('flujo administrador y operador móvil sincronizados', async ({ page, browser }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByLabel('Correo electrónico', { exact: true }).fill('admin@test.local');
  await page.getByLabel('Contraseña', { exact: true }).fill('admin-ui-test-password');
  await page.getByRole('button', { name: 'Ingresar al espacio' }).click();
  await expect(page.locator('#stat-total')).toHaveText('12');
  await page.getByRole('button', { name: 'Acceso operarios', exact: true }).click();
  await page.getByRole('button', { name: 'Asignar operarios', exact: true }).click();
  await expect(page.getByLabel('operator@test.local')).toBeChecked();
  await page.getByLabel('operator@test.local').uncheck();
  await page.getByRole('button', { name: 'Guardar accesos', exact: true }).click();
  await page.getByRole('button', { name: 'Asignar operarios', exact: true }).click();
  await page.getByLabel('operator@test.local').check();
  await page.getByRole('button', { name: 'Guardar accesos', exact: true }).click();
  await page.getByRole('button', { name: 'Resumen', exact: true }).click();
  await page.screenshot({ path: 'test-results/dashboard-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Invitados', exact: true }).click();
  await page.getByRole('button', { name: '+ Invitado', exact: true }).click();
  await page.getByLabel('Nombre completo').fill('Invitada Prueba');
  await page.locator('#modal').getByLabel('Correo electrónico', { exact: true }).fill('prueba@example.com');
  await page.getByRole('button', { name: 'Guardar invitado', exact: true }).click();
  await expect(page.locator('#stat-total')).toHaveText('13');
  await expect(page.locator('#mail-summary')).toContainText('Por enviar');
  await page.getByLabel('Filtrar correos').selectOption('sent');
  await expect(page.locator('#list-count')).toHaveText('0 de 13 invitados');
  await page.getByLabel('Filtrar correos').selectOption('pending');
  await page.getByLabel('Buscar invitados', { exact: true }).fill('Invitada Prueba');
  await page.getByRole('button', { name: 'Ver invitación', exact: true }).click();
  const invitation = page.frameLocator('#invitation-preview');
  await expect(invitation.getByRole('img', { name: 'QR personal de ingreso de Invitada Prueba' })).toBeVisible();
  await expect(invitation.getByText('Hola, Invitada Prueba.')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Enviar invitación', exact: true })).toBeDisabled();
  const preview = await page.locator('#invitation-preview').getAttribute('srcdoc');
  const png = PNG.sync.read(Buffer.from(preview.match(/src="data:image\/png;base64,([^"]+)"/)[1], 'base64'));
  const qr = jsQR(new Uint8ClampedArray(png.data), png.width, png.height).data;
  const emailPage = await page.context().newPage();
  await emailPage.setViewportSize({ width: 620, height: 1100 });
  await emailPage.setContent(preview);
  await emailPage.screenshot({ path: 'test-results/invitacion-correo.png', fullPage: true });
  await emailPage.setViewportSize({ width: 375, height: 812 });
  expect(await emailPage.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await emailPage.close();
  await expect(page.getByText('Envío de correo pendiente de configuración SMTP.')).toBeVisible();
  await page.getByRole('button', { name: 'Cerrar', exact: true }).click();
  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const mobile = await mobileContext.newPage(); await mobile.goto('http://localhost:3100/acreditacion/');
  const operatorRequests = []; mobile.on('request', request => { if (request.url().includes('/api/')) operatorRequests.push(new URL(request.url()).pathname); });
  await mobile.getByLabel('Correo del operario', { exact: true }).fill('operator@test.local');
  await mobile.getByLabel('Contraseña', { exact: true }).fill('operator-ui-test-password');
  await mobile.getByRole('button', { name: 'Entrar a acreditación' }).click();
  await expect(mobile.locator('#access-view')).toBeVisible();
  await expect(mobile.locator('#event-name')).toHaveText('Encuentro Agency 2026');
  await expect(mobile.getByText('Resumen', { exact: true })).toHaveCount(0);
  await expect(mobile.getByText('Invitados', { exact: true })).toHaveCount(0);
  await expect(mobile.getByText('Correos CSV')).toHaveCount(0);
  await mobile.screenshot({ path: 'test-results/operario-escaner.png', fullPage: true });
  await mobile.getByRole('tab', { name: 'Buscar persona' }).click();
  await expect(mobile.getByRole('button', { name: '+ Crear evento' })).toBeHidden();
  await mobile.getByLabel('Nombre, RUT o correo').fill('Invitada Prueba');
  await mobile.getByRole('button', { name: 'Acreditar', exact: true }).click();
  await mobile.getByRole('button', { name: 'Confirmar acreditación' }).click();
  await expect(mobile.locator('#checkin-result')).toContainText('ACREDITADO');
  await expect(page.locator('#stat-checked')).toHaveText('1');
  await page.getByRole('button', { name: 'Ver ficha', exact: true }).click();
  await expect(page.locator('#modal')).toContainText('Ingreso registrado');
  await expect(page.locator('#modal')).toContainText('operator@test.local');
  await expect(page.locator('#modal')).toContainText('No hay intentos de envío registrados');
  await page.screenshot({ path: 'test-results/ficha-invitado.png', fullPage: true });
  await page.getByRole('button', { name: 'Cerrar', exact: true }).click();
  expect(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await mobile.screenshot({ path: 'test-results/acreditacion-mobile.png', fullPage: true });
  await mobile.getByRole('tab', { name: 'Escanear QR' }).click();
  await mobile.getByText('Ingresar código QR manualmente', { exact: true }).click();
  await mobile.getByLabel('Código QR', { exact: true }).fill(qr);
  await mobile.getByRole('button', { name: 'Validar código', exact: true }).click();
  await expect(mobile.locator('#checkin-result')).toContainText('YA INGRESÓ');
  await mobile.getByLabel('Código QR', { exact: true }).fill('invalido');
  await mobile.getByRole('button', { name: 'Validar código', exact: true }).click();
  await expect(mobile.locator('#checkin-result')).toContainText('QR INVÁLIDO');
  await mobile.route('**/api/operator/events/*/checkin', route => route.abort());
  await mobile.getByLabel('Código QR', { exact: true }).fill(qr);
  await mobile.getByRole('button', { name: 'Validar código', exact: true }).click();
  await expect(mobile.locator('#checkin-result')).toContainText('INGRESO NO CONFIRMADO');
  expect(operatorRequests.every(path => path.startsWith('/api/operator/'))).toBe(true);
  await mobileContext.close();
  await page.getByRole('button', { name: 'Resumen', exact: true }).click();
  await expect(page.locator('#arrivals')).toContainText('Invitada Prueba');
  expect(errors).toEqual([]);
});
