import { test, expect } from '@playwright/test';
import { PNG } from 'pngjs';
test('diseño, categoría, ficha, confirmación pública y reportes',async({page,browser})=>{
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/');
 await page.getByLabel('Correo electrónico',{exact:true}).fill('admin@test.local');
 await page.getByLabel('Contraseña',{exact:true}).fill('admin-ui-test-password');
 await page.getByRole('button',{name:'Ingresar al espacio'}).click();
 await expect(page.locator('#workspace')).toBeVisible();
 const headers={'X-Requested-With':'eventos'};
 const event=await (await page.request.post('/api/events',{headers,data:{name:'Presentación de nueva temporada',date:'2026-10-22T21:00:00Z',location:'Santiago · Salón principal'}})).json();
 await expect(page.locator('#event-select option', {hasText:'Presentación de nueva temporada'})).toHaveCount(1);
 await page.locator('#event-select').selectOption(String(event.id));
 await expect(page.locator('#event-name')).toHaveText('Presentación de nueva temporada');
 await page.getByRole('button',{name:'Invitados',exact:true}).click();
 await page.getByRole('button',{name:'+ Invitado',exact:true}).click();
 await page.getByLabel('Nombre completo').fill('María Prueba');
 await page.locator('#modal').getByLabel('Correo electrónico',{exact:true}).fill('maria@example.com');
 await page.getByRole('combobox',{name:'Categoría',exact:true}).selectOption('vip');
 await page.getByLabel('Notas internas').fill('Invitada de dirección.');
 await page.getByRole('button',{name:'Guardar invitado',exact:true}).click();
 await expect(page.locator('#guest-rows')).toContainText('VIP');
 await page.getByLabel('Filtrar categoría').selectOption('prensa');
 await expect(page.locator('#list-count')).toHaveText('0 de 1 invitados');
 await page.getByLabel('Filtrar categoría').selectOption('vip');
 await page.getByRole('button',{name:'Ver ficha',exact:true}).click();
 await expect(page.locator('#modal')).toContainText('Invitada de dirección.');
 await expect(page.locator('#modal')).toContainText('Sin respuesta');
 await page.getByRole('button',{name:'Cerrar',exact:true}).click();
 await page.getByRole('button',{name:'Diseño de invitación',exact:true}).click();
 await expect(page.getByLabel('Título principal')).toHaveValue('Nos encontramos muy pronto.');
 await page.getByLabel('Asunto del correo').fill('Te esperamos en el lanzamiento');
 await page.getByLabel('Título principal').fill('Una noche para encontrarnos.');
 await page.getByLabel('Texto de la invitación').fill('Queremos compartir esta nueva etapa contigo.\nConfirma si podrás acompañarnos.');
 const png=new PNG({width:120,height:40});for(let i=0;i<png.data.length;i+=4){png.data[i]=35;png.data[i+1]=72;png.data[i+2]=61;png.data[i+3]=255;}
 await page.locator('#design-logo').setInputFiles({name:'logo.png',mimeType:'image/png',buffer:PNG.sync.write(png)});
 await expect(page.locator('#logo-preview')).toBeVisible();
 await page.getByRole('button',{name:'Vista previa con QR',exact:true}).click();
 const frame=page.frameLocator('#invitation-preview');
 await expect(frame.getByRole('heading',{name:'Una noche para encontrarnos.'})).toBeVisible();
 await expect(frame.getByRole('img',{name:'Logo del evento',exact:true})).toBeVisible();
 await expect(frame.getByRole('link',{name:'Asistiré',exact:true})).toBeVisible();
 const rsvpLink=await frame.getByRole('link',{name:'Asistiré',exact:true}).getAttribute('href');
 await page.screenshot({path:'test-results/diseno-invitacion.png',fullPage:true});
 await page.getByRole('button',{name:'Cerrar',exact:true}).click();
 await page.getByRole('button',{name:'Guardar diseño',exact:true}).click();
 await expect(page.locator('#toast')).toContainText('Diseño guardado');
 await page.reload();
 await page.locator('#event-select').selectOption(String(event.id));
 await page.getByRole('button',{name:'Diseño de invitación',exact:true}).click();
 await expect(page.getByLabel('Asunto del correo')).toHaveValue('Te esperamos en el lanzamiento');
 const visitor=await browser.newContext({viewport:{width:390,height:844}});const rsvp=await visitor.newPage();
 await rsvp.goto(rsvpLink);
 await expect(rsvp.locator('#current')).toHaveText('Aún no has confirmado.');
 await rsvp.getByRole('button',{name:'Guardar respuesta'}).click();
 await expect(rsvp.locator('#current')).toContainText('Respuesta guardada.');
 await rsvp.screenshot({path:'test-results/confirmacion-movil.png',fullPage:true});
 expect(await rsvp.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.getByRole('button',{name:'Resumen',exact:true}).click();
 await expect(page.locator('#event-summary article').filter({hasText:'Confirmados'}).locator('strong')).toHaveText('1');
 await expect(page.locator('#stat-checked')).toHaveText('0');
 await page.screenshot({path:'test-results/resumen-administracion.png',fullPage:true});
 await page.getByRole('button',{name:'Invitados',exact:true}).click();
 await page.getByLabel('Filtrar confirmación').selectOption('yes');
 await expect(page.locator('#list-count')).toHaveText('1 de 1 invitados');
 const report=await page.request.get(`/api/events/${event.id}/report.csv`);expect(await report.text()).toContain('Asistirá');
 await page.getByRole('button',{name:'Correos',exact:true}).click();
 await expect(page.getByRole('button',{name:'Enviar prueba',exact:true})).toBeDisabled();
 await expect(page.getByRole('button',{name:'Preparar envío masivo',exact:true})).toBeDisabled();
 await expect(page.locator('#mail-config')).toContainText('pendiente');
 await visitor.close();expect(errors).toEqual([]);
});
